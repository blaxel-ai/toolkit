func TestImageStorageQuotaWithNumericCodeIsNotRetried(t *testing.T) {
	msg := "Image storage quota reached: 51200/51200 MiB used by images across your workspaces. Delete unused images before building again, or request additional quota at https://app.blaxel.ai/account/plan-quotas?id=acc"
	err, calls := createSandboxAgainst(t, 2, func(w http.ResponseWriter, r *http.Request) {
		w.Header().Set("Content-Type", "application/json")
		w.WriteHeader(http.StatusTooManyRequests)
		_, _ = w.Write([]byte(`{"error":"` + msg + `","code":429}`))
	})
	require.Error(t, err)
	assert.Equal(t, int32(1), calls, "an image storage quota must not be retried")
	assert.Equal(t, msg+" (HTTP 429): not retryable until usage drops or the quota is raised: https://docs.blaxel.ai/Security/Quotas", extractErrorMessage(err))
}

